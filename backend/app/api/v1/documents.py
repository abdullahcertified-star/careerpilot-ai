"""FastAPI router for job-tailored resume and cover letter generation, editing,
version history, factual consistency reports, and document export.
"""

import logging
from typing import List, Optional
from fastapi import APIRouter, Depends, HTTPException, Query, Response, status
from sqlalchemy.ext.asyncio import AsyncSession

from app.api.deps import get_current_user
from app.core.database import get_db
from app.models.entities import User
from app.services.documents.document_service import document_service
from app.services.documents.resume_agent import MissingAIConfigurationError
from app.services.documents.schemas import (
    DocumentGenerateRequest,
    DocumentUpdateRequest,
    DocumentVersionResponse,
    FactualValidationReport,
    GeneratedDocumentResponse,
)

logger = logging.getLogger(__name__)

router = APIRouter(prefix="/documents", tags=["Document Generation & Studio"])


def _to_doc_response(doc) -> GeneratedDocumentResponse:
    """Helper formatting GeneratedDocument and latest version response."""
    latest_ver = doc.versions[0] if doc.versions else None
    latest_resp = None
    if latest_ver:
        latest_resp = DocumentVersionResponse(
            id=latest_ver.id,
            document_id=latest_ver.document_id,
            version_number=latest_ver.version_number,
            structured_data=latest_ver.structured_data,
            formatted_text=latest_ver.formatted_text,
            model_name=latest_ver.model_name,
            prompt_version=latest_ver.prompt_version,
            validation_report=FactualValidationReport.model_validate(latest_ver.validation_report),
            is_approved=latest_ver.is_approved,
            change_summary=latest_ver.change_summary,
            created_at=latest_ver.created_at,
        )

    return GeneratedDocumentResponse(
        id=doc.id,
        user_id=doc.user_id,
        job_id=doc.job_id,
        doc_type=doc.doc_type,
        title=doc.title,
        template_id=doc.template_id,
        candidate_profile_version=doc.candidate_profile_version,
        created_at=doc.created_at,
        updated_at=doc.updated_at,
        latest_version=latest_resp,
        versions_count=len(doc.versions) if doc.versions else 1,
        job_title=doc.job.title if doc.job else None,
        job_company=doc.job.company if doc.job else None,
    )


@router.post("/generate", response_model=GeneratedDocumentResponse, status_code=status.HTTP_201_CREATED)
async def generate_document(
    payload: DocumentGenerateRequest,
    require_live_llm: bool = Query(False, description="Require active LLM credentials"),
    current_user: User = Depends(get_current_user),
    db: AsyncSession = Depends(get_db),
):
    """
    Generates a tailored resume or cover letter for a job requisition.
    Validates content against verified candidate facts and creates an initial version.
    """
    try:
        doc, version = await document_service.generate_document(
            session=db,
            user_id=current_user.id,
            job_id=payload.job_id,
            doc_type=payload.doc_type,
            template_id=payload.template_id,
            custom_instructions=payload.custom_instructions,
            require_live_llm=require_live_llm,
        )
        return _to_doc_response(doc)
    except MissingAIConfigurationError as exc:
        raise HTTPException(
            status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
            detail=str(exc),
        )
    except ValueError as exc:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail=str(exc))
    except Exception as exc:
        logger.error("Error generating document: %s", exc)
        raise HTTPException(status_code=status.HTTP_500_INTERNAL_SERVER_ERROR, detail=str(exc))


@router.get("", response_model=List[GeneratedDocumentResponse])
async def list_documents(
    job_id: Optional[int] = Query(None, description="Filter by job ID"),
    doc_type: Optional[str] = Query(None, description="Filter by doc type ('resume' or 'cover_letter')"),
    current_user: User = Depends(get_current_user),
    db: AsyncSession = Depends(get_db),
):
    """Lists all tailored documents generated by the authenticated user."""
    docs = await document_service.list_user_documents(
        session=db,
        user_id=current_user.id,
        job_id=job_id,
        doc_type=doc_type,
    )
    return [_to_doc_response(d) for d in docs]


@router.get("/{document_id}", response_model=GeneratedDocumentResponse)
async def get_document(
    document_id: int,
    current_user: User = Depends(get_current_user),
    db: AsyncSession = Depends(get_db),
):
    """Retrieves document detail and latest version with ownership check."""
    try:
        doc = await document_service.get_document(db, current_user.id, document_id)
        return _to_doc_response(doc)
    except PermissionError:
        raise HTTPException(
            status_code=status.HTTP_403_FORBIDDEN,
            detail="Access to requested document is denied.",
        )


@router.get("/{document_id}/versions", response_model=List[DocumentVersionResponse])
async def list_document_versions(
    document_id: int,
    current_user: User = Depends(get_current_user),
    db: AsyncSession = Depends(get_db),
):
    """Retrieves the complete revision history and validation reports for a document."""
    try:
        doc = await document_service.get_document(db, current_user.id, document_id)
        return [
            DocumentVersionResponse(
                id=v.id,
                document_id=v.document_id,
                version_number=v.version_number,
                structured_data=v.structured_data,
                formatted_text=v.formatted_text,
                model_name=v.model_name,
                prompt_version=v.prompt_version,
                validation_report=FactualValidationReport.model_validate(v.validation_report),
                is_approved=v.is_approved,
                change_summary=v.change_summary,
                created_at=v.created_at,
            )
            for v in doc.versions
        ]
    except PermissionError:
        raise HTTPException(
            status_code=status.HTTP_403_FORBIDDEN,
            detail="Access to requested document is denied.",
        )


@router.put("/{document_id}/versions", response_model=DocumentVersionResponse, status_code=status.HTTP_201_CREATED)
async def edit_document_content(
    document_id: int,
    payload: DocumentUpdateRequest,
    current_user: User = Depends(get_current_user),
    db: AsyncSession = Depends(get_db),
):
    """
    Edits document structured data and creates a NEW version.
    Re-runs automated factual validation against candidate verified facts.
    """
    try:
        new_version = await document_service.edit_document_content(
            session=db,
            user_id=current_user.id,
            document_id=document_id,
            update_data=payload,
        )

        # Invalidate any human approval granted to applications linked to this edited document
        from app.services.workflow.service import WorkflowService
        await WorkflowService().invalidate_approval_on_document_edit(
            db, current_user.id, document_id, new_version.id
        )

        return DocumentVersionResponse(
            id=new_version.id,
            document_id=new_version.document_id,
            version_number=new_version.version_number,
            structured_data=new_version.structured_data,
            formatted_text=new_version.formatted_text,
            model_name=new_version.model_name,
            prompt_version=new_version.prompt_version,
            validation_report=FactualValidationReport.model_validate(new_version.validation_report),
            is_approved=new_version.is_approved,
            change_summary=new_version.change_summary,
            created_at=new_version.created_at,
        )
    except PermissionError:
        raise HTTPException(
            status_code=status.HTTP_403_FORBIDDEN,
            detail="Access to requested document is denied.",
        )
    except ValueError as exc:
        raise HTTPException(status_code=status.HTTP_422_UNPROCESSABLE_ENTITY, detail=str(exc))


@router.get("/{document_id}/download")
async def download_document(
    document_id: int,
    version_id: Optional[int] = Query(None, description="Optional version ID to download"),
    format: str = Query("pdf", description="Export format: 'pdf' or 'docx'"),
    current_user: User = Depends(get_current_user),
    db: AsyncSession = Depends(get_db),
):
    """
    Streams a downloadable DOCX or text-selectable PDF document file.
    Enforces user ownership.
    """
    try:
        content_bytes, filename, media_type = await document_service.render_export_file(
            session=db,
            user_id=current_user.id,
            document_id=document_id,
            version_id=version_id,
            export_format=format,
        )
        return Response(
            content=content_bytes,
            media_type=media_type,
            headers={
                "Content-Disposition": f'attachment; filename="{filename}"',
            },
        )
    except PermissionError:
        raise HTTPException(
            status_code=status.HTTP_403_FORBIDDEN,
            detail="Access to requested document is denied.",
        )
    except ValueError as exc:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail=str(exc))
